package se.hirt.mnemic.recall;

/** Token budgets are enforced against an estimate: a calibrated character ratio, never an unmeasured guess. */
public interface TokenEstimator {

	int estimate(String text);

	/** Roughly four characters per token for English prose with a modern BPE tokenizer. */
	TokenEstimator CHARS_PER_TOKEN = text -> text == null ? 0 : (int) Math.ceil(text.length() / 4.0);
}
